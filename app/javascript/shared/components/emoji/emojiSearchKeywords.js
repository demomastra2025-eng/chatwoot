function lookupKeywordsForEmoji(emojiChar = '') {
  const stripped = String(emojiChar).replace(/\uFE0F/g, '');
  return (
    EMOJI_RU_KEYWORDS[emojiChar] ||
    EMOJI_RU_KEYWORDS[stripped] ||
    EMOJI_RU_KEYWORDS[`${stripped}\uFE0F`] ||
    ''
  );
}

export function enrichEmojiCategories(rawCategories = []) {
  return rawCategories.map(category => {
    const existingSet = new Set(category.emojis.map(item => item.emoji));
    const extras = (
      EXTRA_MODERN_EMOJIS_BY_CATEGORY[category.slug] || []
    ).filter(item => !existingSet.has(item.emoji));
    const merged = [...category.emojis, ...extras].map(item => {
      const ruKeywords = lookupKeywordsForEmoji(item.emoji);
      const searchText =
        `${item.name || ''} ${(item.slug || '').replaceAll('_', ' ')} ${ruKeywords}`
          .toLowerCase()
          .trim();
      return {
        ...item,
        searchText,
      };
    });

    return {
      ...category,
      emojis: merged,
    };
  });
}

export function matchesEmojiSearch(item, query) {
  const normalizedQuery = String(query || '')
    .toLowerCase()
    .trim();
  if (!normalizedQuery) return true;

  const haystack =
    item.searchText ||
    `${item.name || ''} ${(item.slug || '').replaceAll('_', ' ')} ${lookupKeywordsForEmoji(
      item.emoji
    )}`.toLowerCase();

  return normalizedQuery.split(/\s+/).every(token => haystack.includes(token));
}
