const EMOJI_SEQUENCE_REGEX =
  /(?:\p{RI}\p{RI}|[#*0-9]\uFE0F?\u20E3|(?:\p{Emoji_Presentation}|\p{Extended_Pictographic})(?:\uFE0F|[\u{1F3FB}-\u{1F3FF}])?(?:\u200D(?:\p{Emoji_Presentation}|\p{Extended_Pictographic})(?:\uFE0F|[\u{1F3FB}-\u{1F3FF}])?)*)/gu;

export function emojiToAppleUnified(emoji) {
  const raw = String(emoji || "").trim();
  if (!raw) return "";

  const parts = Array.from(raw).map(c => c.codePointAt(0).toString(16));
  const hasFe0fOrKeycap = parts.includes("fe0f") || parts.includes("20e3");
  const formattedParts = parts.map(p =>
    hasFe0fOrKeycap && p.length < 4 ? p.padStart(4, "0") : p
  );
  const candidate = formattedParts.join("-");
  if (NON_QUALIFIED_TO_UNIFIED[candidate]) {
    return NON_QUALIFIED_TO_UNIFIED[candidate];
  }

  const paddedCandidate = parts.map(p => p.padStart(4, "0")).join("-");
  if (NON_QUALIFIED_TO_UNIFIED[paddedCandidate]) {
    return NON_QUALIFIED_TO_UNIFIED[paddedCandidate];
  }

  return candidate;
}

export function getAppleEmojiUrl(emoji) {
  const unified = emojiToAppleUnified(emoji);
  if (!unified) return "";
  return `${APPLE_EMOJI_CDN_BASE}/${unified}.png`;
}

export function isJumboEmojiText(text) {
  const trimmed = String(text || "").trim();
  if (!trimmed) return false;

  const matches = trimmed.match(EMOJI_SEQUENCE_REGEX);
  if (!matches || matches.length < 1 || matches.length > 3) return false;

  const remainder = trimmed.replace(EMOJI_SEQUENCE_REGEX, "").replace(/\s+/g, "");
  return remainder.length === 0;
}

export function replaceEmojisWithAppleImages(html, { jumbo = false } = {}) {
  if (!html || typeof html !== "string") return html;

  const sizeClass = jumbo ? "apple-emoji--jumbo" : "apple-emoji--inline";
  // Split by HTML tags and preserve code/pre blocks
  const tokens = html.split(/(<[^>]+>)/g);
  let insideSkipTag = 0;

  return tokens
    .map(token => {
      if (token.startsWith("<")) {
        const lower = token.toLowerCase();
        if (lower.startsWith("<code") || lower.startsWith("<pre")) {
          insideSkipTag += 1;
        } else if (lower.startsWith("</code") || lower.startsWith("</pre")) {
          insideSkipTag = Math.max(0, insideSkipTag - 1);
        }
        return token;
      }

      if (insideSkipTag > 0) return token;

      return token.replace(EMOJI_SEQUENCE_REGEX, match => {
        const url = getAppleEmojiUrl(match);
        if (!url) return match;
        return `<img src="${url}" alt="${match}" class="apple-emoji ${sizeClass} skip-context-menu" draggable="false" loading="lazy" />`;
      });
    })
    .join("");
}
